export type { Dict };
export function dict(site: Site): Dict {
  return site === 'english' ? en : vi;
}

export function errorText(d: Dict, status: number, error?: string): string {
  if (status === 429) return d.errors.too_many;
  if (error && error in d.errors) return d.errors[error as keyof Dict['errors']];
  return d.errors.generic;
}
